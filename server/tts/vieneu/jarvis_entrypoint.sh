#!/bin/sh
# Jarvis wrapper around the VieNeu speech API.
# 1. Hugging Face offline mode (JARVIS_HF_OFFLINE = compose TTS_HF_OFFLINE): VieNeu loads its model
#    and the MOSS audio codec with trust_remote_code and no revision pin, so while online every start
#    re-resolves "main" of two third-party repos and runs their current code. "auto" (default) goes
#    offline as soon as both repos are in the cache (trust on first use); 1 = always offline,
#    0 = always online (needed once after changing the model, the device or the backend).
# 2. Voices: VieNeu loads its presets only from the package asset voices_v3_turbo.json, and voices
#    enrolled with POST /v1/voices live in process memory. To persist cloned voices, mount a
#    directory with a voices file generated by /opt/jarvis/clone_voice.py and point
#    VIENEU_VOICES_FILE at it; without a (valid) file the built-in presets are used.
set -e

ASSET_DIR=/workspace/src/vieneu/assets
ASSET="$ASSET_DIR/voices_v3_turbo.json"
BUILTIN="$ASSET_DIR/voices_v3_turbo.builtin.json"
HF_REPOS="pnnbao-ump--VieNeu-TTS-v3-Turbo OpenMOSS-Team--MOSS-Audio-Tokenizer-Nano"

# hf_cached REPO_DIR: the repo has a resolved "main" and at least one snapshot in the HF cache.
hf_cached() {
    dir="${HF_HOME:-$HOME/.cache/huggingface}/hub/models--$1"
    [ -s "$dir/refs/main" ] && [ -n "$(ls -A "$dir/snapshots" 2>/dev/null)" ]
}

mode="${JARVIS_HF_OFFLINE:-auto}"
case "$mode" in
    1 | true | TRUE | yes | on) offline=1; why="forced" ;;
    0 | false | FALSE | no | off) offline=0; why="forced" ;;
    *)
        offline=1
        why="auto: model and codec found in the cache"
        for repo in $HF_REPOS; do
            if ! hf_cached "$repo"; then
                offline=0
                why="auto: $repo not cached yet, downloading"
            fi
        done
        ;;
esac
# huggingface_hub reads only 1/ON/YES/TRUE as true: always export an explicit 0 or 1.
HF_HUB_OFFLINE=$offline
export HF_HUB_OFFLINE
echo "jarvis: HF_HUB_OFFLINE=$offline ($why; TTS_HF_OFFLINE=$mode)"

if [ -n "${VIENEU_VOICES_FILE:-}" ] && [ -f "$VIENEU_VOICES_FILE" ]; then
    if python -c 'import json, sys; d = json.load(open(sys.argv[1], encoding="utf-8")); sys.exit(0 if isinstance(d.get("presets"), dict) and d["presets"] else 1)' "$VIENEU_VOICES_FILE"; then
        cp -f "$VIENEU_VOICES_FILE" "$ASSET"
        echo "jarvis: voices loaded from $VIENEU_VOICES_FILE"
    else
        cp -f "$BUILTIN" "$ASSET"
        echo "jarvis: WARNING invalid voices file $VIENEU_VOICES_FILE, using built-in voices" >&2
    fi
elif [ -f "$BUILTIN" ]; then
    # Restore the built-ins in case a previous run of this container installed a custom file.
    cp -f "$BUILTIN" "$ASSET"
fi

exec "$@"
