bool JarvisHudDisplay::Impl::Offline() const {
    // Scanning for Wi-Fi during boot is not "offline" yet (the board reports a lost link or
    // an unreachable server through SetOffline()).
    const char* icon_now = net_icon.load(std::memory_order_relaxed);
    bool wifi_down = mode != Mode::kBoot && icon_now != nullptr &&
                     strcmp(icon_now, MATERIAL_SYMBOLS_WIFI_OFF) == 0;
    return wifi_down || server_error || offline_in.load(std::memory_order_relaxed);
}

Visual JarvisHudDisplay::Impl::ResolveVisual() const {
    switch (mode) {
        case Mode::kListening:
            return Visual::kListening;
        case Mode::kThinking:
            return Visual::kThinking;
        case Mode::kSpeaking:
            return Visual::kSpeaking;
        case Mode::kError:
            return Visual::kAlert;
        case Mode::kIdle:
            return Offline() ? Visual::kAlert : Visual::kIdle;
        case Mode::kConnecting:
            return Visual::kConnecting;  // an attempt is in progress
        case Mode::kBoot:
        default:
            return Visual::kBoot;  // boot keeps its own progress visual even while offline
    }
}

void JarvisHudDisplay::Impl::ApplyVisual() {
    if (root == nullptr) {
        return;
    }
    visual = ResolveVisual();
    visual_valid = true;

    uint32_t color = kColorCyan;
    lv_opa_t track = 40;
    if (visual == Visual::kThinking) {
        color = kColorAmber;
    } else if (visual == Visual::kAlert) {
        color = kColorRed;
        track = 30;
    } else if (visual == Visual::kIdle || visual == Visual::kBoot) {
        track = 28;
    }
    // Emotion tints the inner ring and the core unless the state colour carries meaning.
    const bool tinted = tint != 0 && visual != Visual::kThinking && visual != Visual::kAlert;
    const uint32_t inner = tinted ? tint : color;

    for (int i = 0; i < 3; ++i) {
        lv_obj_set_style_arc_color(ring[i], Hex(i == 2 ? inner : color), LV_PART_MAIN);
        lv_obj_set_style_arc_color(ring[i], Hex(i == 2 ? inner : color), LV_PART_INDICATOR);
        lv_obj_set_style_arc_opa(ring[i], track, LV_PART_MAIN);
        SetRingRotation(i, 0);
        SetRingAngles(i, kRings[i].start, kRings[i].start + kRings[i].span);
        SetRingWidth(i, kRings[i].width);
        SetRingOpa(i, visual == Visual::kBoot ? 170 : LV_OPA_COVER);
    }
    lv_obj_set_style_border_color(core, Hex(inner), 0);
    SetCoreOpa(LV_OPA_COVER);
    lv_obj_set_style_text_color(core_text, Hex(color), 0);
    lv_obj_set_style_text_color(core_icon, Hex(tinted ? tint : color), 0);

    const bool speaking = visual == Visual::kSpeaking;
    tick_color = Hex(speaking ? color : (visual == Visual::kAlert ? kColorRed : kColorCyanDim));
    tick_opa = LV_OPA_COVER;
    uint8_t idle[kTickCount];
    std::fill(std::begin(idle), std::end(idle), static_cast<uint8_t>(kTickIdleLen));
    SetTickLengths(idle);
    lv_obj_invalidate(ticks);  // colour change

    if (icon != nullptr) {
        lv_label_set_text(core_icon, icon);
        lv_obj_remove_flag(core_icon, LV_OBJ_FLAG_HIDDEN);
        lv_obj_add_flag(core_text, LV_OBJ_FLAG_HIDDEN);
    } else {
        lv_obj_add_flag(core_icon, LV_OBJ_FLAG_HIDDEN);
        lv_obj_remove_flag(core_text, LV_OBJ_FLAG_HIDDEN);
    }
}

// Re-applies colours and geometry only when the resolved visual changes, so repeated status
// texts do not restart the running animation.
void JarvisHudDisplay::Impl::UpdateVisual() {
    if (!visual_valid || ResolveVisual() != visual) {
        ApplyVisual();
    }
}

void JarvisHudDisplay::Impl::RefreshCaption(uint32_t now) {
    if (caption == nullptr) {
        return;
    }
    if (has_notification && static_cast<int32_t>(notification_until - now) <= 0) {
        has_notification = false;
    }
    const char* text = status_text.c_str();
    uint32_t color = kColorCyan;
    switch (visual) {
        case Visual::kIdle:
            color = kColorTextDim;
            break;
        case Visual::kThinking:
            color = kColorAmber;
            text = TextThinking();
            break;
        case Visual::kAlert:
            color = kColorRed;
            if (mode != Mode::kError) {
                const char* icon_now = net_icon.load(std::memory_order_relaxed);
                if (icon_now != nullptr && strcmp(icon_now, MATERIAL_SYMBOLS_WIFI_OFF) == 0) {
                    text = TextNoWifi();
                } else if (server_error) {
                    text = TextNoServer();
                } else {
                    text = TextOffline();
                }
            }
            break;
        default:
            break;
    }
    if (has_notification) {
        text = notification.c_str();
        color = kColorCyan;
    }
    if (caption_shown != text) {
        caption_shown = text;
        lv_label_set_text(caption, caption_shown.c_str());
    }
    if (caption_color != color) {
        caption_color = color;
        lv_obj_set_style_text_color(caption, Hex(color), 0);
    }
}

void JarvisHudDisplay::Impl::SetReply(const char* text, bool system, uint32_t now) {
    if (reply_label == nullptr) {
        return;
    }
    std::string clipped = Clip(text, kMaxReplyBytes);
    lv_label_set_text(reply_label, clipped.c_str());
    if (system != reply_is_system) {
        reply_is_system = system;
        lv_obj_set_style_text_color(reply_label, Hex(system ? kColorAmber : kColorTextBright), 0);
    }
    reply_scroll.Reset(now);
}

void JarvisHudDisplay::Impl::OnStatus(const char* status, uint32_t now) {
    namespace S = Lang::Strings;
    status_text = Clip(status, kMaxCaptionBytes);
    has_notification = false;  // like upstream: a new status replaces the notification

    const bool had_server_error = server_error;
    if (strcmp(status, S::STANDBY) == 0) {
        SetMode(Mode::kIdle, now);
    } else if (strcmp(status, S::LISTENING) == 0) {
        server_error = false;  // a working session proves the server is reachable
        SetMode(Mode::kListening, now);
    } else if (strcmp(status, S::SPEAKING) == 0) {
        server_error = false;
        if (mode == Mode::kThinking) {
            // "tts start" follows the STT text at once; keep thinking until the reply
            // actually starts (first sentence or audio, see OnChatMessage / Tick).
            reply_pending = true;
        } else {
            SetMode(Mode::kSpeaking, now);
        }
    } else if (strcmp(status, S::CONNECTING) == 0) {
        SetMode(Mode::kConnecting, now);
    } else if (strcmp(status, S::ERROR) == 0) {
        SetMode(Mode::kError, now);
    } else if (strcmp(status, S::LOADING_PROTOCOL) == 0 || strcmp(status, S::ACTIVATION) == 0) {
        // Both follow the OTA check, but LOADING_PROTOCOL also comes when the activation task
        // gave up retrying: only a real answer clears the server error.
        if (Application::GetInstance().OtaCheckSucceeded()) {
            server_error = false;
        }
        SetMode(Mode::kBoot, now);
    } else if (strcmp(status, S::INITIALIZING) == 0 ||
               strcmp(status, S::CHECKING_NEW_VERSION) == 0 ||
               strcmp(status, S::WIFI_CONFIG_MODE) == 0 ||
               strcmp(status, S::LOADING_ASSETS) == 0 || strcmp(status, S::UPGRADING) == 0 ||
               strcmp(status, S::OTA_UPGRADE) == 0) {
        SetMode(Mode::kBoot, now);
    }
    if (mode != Mode::kThinking) {
        reply_pending = false;
    }
    if (had_server_error != server_error) {
        status_dirty.store(true, std::memory_order_relaxed);  // refresh the OFFLINE badge
    }
    // Other texts (server alerts, ...) only change the caption.
    UpdateVisual();
    RefreshCaption(now);
}

void JarvisHudDisplay::Impl::OnChatMessage(const char* role, const char* content, uint32_t now) {
    if (strcmp(role, "user") == 0) {
        if (content[0] == '\0') {
            lv_label_set_text(user_label, "");
            return;
        }
        std::string line = "\xC2\xBB " + Clip(content, kMaxUserBytes);  // "» "
        lv_label_set_text(user_label, line.c_str());
        // Speech was recognised: the LLM is working until the reply starts.
        if (mode == Mode::kListening || mode == Mode::kIdle || mode == Mode::kConnecting) {
            SetMode(Mode::kThinking, now);
            reply_pending = false;
            // A new turn: the previous answer must not read as the answer to this question.
            SetReply("", false, now);
            UpdateVisual();
            RefreshCaption(now);
        }
    } else if (strcmp(role, "assistant") == 0) {
        SetReply(content, false, now);
        if (content[0] != '\0' && mode == Mode::kThinking && reply_pending) {
            // tts sentence_start comes right before that sentence's audio.
            SetMode(Mode::kSpeaking, now);
            reply_pending = false;
            UpdateVisual();
            RefreshCaption(now);
        }
    } else if (content[0] == '\0') {
        // Upstream clears the whole subtitle with an empty system message (session start/end).
        lv_label_set_text(user_label, "");
        SetReply("", false, now);
    } else {
        namespace S = Lang::Strings;
        SetReply(content, true, now);
        // Server connection errors arrive as "<message>\n<url>"; OTA failures use a format
        // string, so compare its fixed part only.
        const char* ota_failed = S::CHECK_NEW_VERSION_FAILED;
        const char* fmt = strchr(ota_failed, '%');
        size_t ota_len = fmt != nullptr ? static_cast<size_t>(fmt - ota_failed) : 0;
        if (StartsWith(content, S::SERVER_NOT_CONNECTED) ||
            StartsWith(content, S::SERVER_TIMEOUT) || StartsWith(content, S::SERVER_ERROR) ||
            StartsWith(content, ota_failed, ota_len)) {
            server_error = true;
            status_dirty.store(true, std::memory_order_relaxed);
            UpdateVisual();
            RefreshCaption(now);
        }
    }
}

void JarvisHudDisplay::Impl::OnEmotion(const char* emotion) {
    uint32_t new_tint = 0;
    const char* new_icon = nullptr;
    if (emotion != nullptr && emotion[0] != '\0' && strcmp(emotion, "neutral") != 0 &&
        strcmp(emotion, "robot_2") != 0) {
        bool found = false;
        for (const auto& e : kEmotions) {
            if (strcmp(e.name, emotion) == 0) {
                new_tint = e.tint;
                new_icon = e.icon;
                found = true;
                break;
            }
        }
        if (!found) {
            new_icon = material_symbols_get_utf8(emotion);  // any other icon name
        }
        if (strcmp(emotion, "cloud_off") == 0) {
            server_error = true;  // OTA/server check failed
            status_dirty.store(true, std::memory_order_relaxed);
        }
    }
    if (new_tint != tint || new_icon != icon) {
        tint = new_tint;
        icon = new_icon;
        ApplyVisual();
        RefreshCaption(lv_tick_get());
    }
}

void JarvisHudDisplay::Impl::OnInfo(const std::string& title, const std::string& text,
                                    int seconds, uint32_t now) {
    if (card == nullptr) {
        return;
    }
    std::string t = Clip(title.c_str(), kMaxTitleBytes);
    std::string body = Clip(text.c_str(), kMaxInfoBytes);
    lv_label_set_text(card_title, t.c_str());
    lv_label_set_text(card_text, body.c_str());
    lv_obj_update_layout(card_text);

    const int title_h = 4 + vi16->font()->line_height;
    const int line = vi14->font()->line_height;
    const int max_text_h = (kCardMaxH - title_h - kCardPad) / line * line;  // whole lines
    const int text_h = static_cast<int>(lv_obj_get_height(card_text));
    card_h = std::clamp(title_h + std::min(text_h, max_text_h) + kCardPad, kCardMinH, kCardMaxH);
    lv_obj_set_height(card, card_h);
    card_scroll.box_h = text_h > max_text_h ? max_text_h : card_h - title_h - kCardPad;
    lv_obj_set_height(lv_obj_get_parent(card_text), card_scroll.box_h);
    card_scroll.Reset(now);

    const int height = static_cast<int>(owner->height_);
    card_y = height - 1 - card_h;
    card_until = now + static_cast<uint32_t>(std::clamp(seconds, 1, 30)) * 1000u;
    if (card_state == Card::kHidden || card_state == Card::kOut) {
        card_state = Card::kIn;
        card_anim_start = now;
        lv_obj_set_y(card, height);
        lv_obj_remove_flag(card, LV_OBJ_FLAG_HIDDEN);
    } else {
        lv_obj_set_y(card, card_y);
    }
}

