void JarvisHudDisplay::Impl::Tick() {
    const uint32_t now = lv_tick_get();

    if (now - last_poll >= kPollPeriodMs) {
        last_poll = now;
        PollSource(now);
    }
    UpdateLevels(now);
    if (mode == Mode::kThinking && reply_pending && spk_metered > kReplyAudioLevel) {
        // Reply audio without a sentence text: it is speaking now.
        SetMode(Mode::kSpeaking, now);
        reply_pending = false;
    }
    UpdatePanels();
    const bool new_second = now - last_status >= kStatusPeriodMs;
    if (new_second) {
        last_status = now;
        // Polled here too: the main loop (UpdateStatusBar) stalls for up to ~10 s while a
        // WebSocket open waits for the server hello. WifiManager getters are thread-safe and
        // never call back into the display.
        net_icon.store(Board::GetInstance().GetNetworkStateIcon(), std::memory_order_relaxed);
    }
    if (new_second || status_dirty.exchange(false)) {
        if (source.vbus_mv) {
            vbus_in.store(source.vbus_mv(), std::memory_order_relaxed);
        }
        UpdateStatusBarWidgets();
    }
    if (now - last_timeout_check >= kTimeoutCheckMs) {
        last_timeout_check = now;
        UpdateModeTimeouts(now);
    }

    UpdateVisual();
    RefreshCaption(now);
    AnimateReactor(now);
    reply_scroll.Tick(now);
    AnimateCard(now);
}

void JarvisHudDisplay::Impl::PollSource(uint32_t now) {
    (void)now;
    if (source.mask_state) {
        mask_in.store(PackMask(source.mask_state()), std::memory_order_relaxed);
    }
    if (source.eyes_state) {
        bool on = false;
        int brightness = 0;
        source.eyes_state(on, brightness);
        eyes_in.store(PackEyes(on, brightness), std::memory_order_relaxed);
    }
}

// Reads a level callback; a value that stops changing means the codec is no longer being
// fed (playback finished, input stopped), so it is treated as silence.
static float ReadLevel(const std::function<float()>& fn, float& raw_prev, uint32_t& changed_at,
                       uint32_t now) {
    if (!fn) {
        return -1.0f;
    }
    float raw = fn();
    if (!(raw >= 0.0f)) {  // also catches NaN
        raw = 0.0f;
    }
    if (raw != raw_prev) {
        raw_prev = raw;
        changed_at = now;
    }
    if (now - changed_at > kLevelStaleMs) {
        return 0.0f;
    }
    return std::min(raw, 1.0f);
}

void JarvisHudDisplay::Impl::UpdateLevels(uint32_t now) {
    float mic = ReadLevel(source.mic_level, mic_raw, mic_changed, now);
    float spk = ReadLevel(source.speaker_level, spk_raw, spk_changed, now);
    spk_metered = spk;
    if (mic < 0.0f) {
        // No meter: a fixed 0.9 s pulse (FW6: use a steady rhythm without a mic level).
        float p = static_cast<float>(now % 900u) / 900.0f;
        mic = 0.35f + 0.25f * std::sin(p * 6.2831853f);
    }
    if (spk < 0.0f) {
        // No meter: a speech-like envelope from two incommensurate periods.
        float a = static_cast<float>(now % 700u) / 700.0f;
        float b = static_cast<float>(now % 2730u) / 2730.0f;
        spk = 0.45f + 0.35f * std::fabs(std::sin(a * 6.2831853f)) *
                          (0.6f + 0.4f * std::sin(b * 6.2831853f));
    }
    mic_level = mic;
    spk_level = spk;
}

void JarvisHudDisplay::Impl::UpdateStatusBarWidgets() {
    if (root == nullptr) {
        return;
    }
    // Clock (system time is set from the OTA server response).
    time_t now = time(nullptr);
    struct tm tm_now = {};
    localtime_r(&now, &tm_now);
    int minute = tm_now.tm_year >= 2025 - 1900
                     ? std::clamp(tm_now.tm_hour, 0, 23) * 60 + std::clamp(tm_now.tm_min, 0, 59)
                     : -1;
    if (minute != shown_minute) {
        shown_minute = minute;
        char buf[16];
        if (minute < 0) {
            snprintf(buf, sizeof(buf), "--:--");
        } else {
            snprintf(buf, sizeof(buf), "%02d:%02d", minute / 60, minute % 60);
        }
        lv_label_set_text(clock_label, buf);
    }

    // Wi-Fi icon and link type.
    const char* icon_now = net_icon.load(std::memory_order_relaxed);
    const bool wifi_down = icon_now != nullptr && strcmp(icon_now, MATERIAL_SYMBOLS_WIFI_OFF) == 0;
    if (icon_now != shown_icon) {
        shown_icon = icon_now;
        lv_label_set_text(wifi_icon, icon_now != nullptr ? icon_now : "");
        lv_obj_set_style_text_color(wifi_icon, Hex(wifi_down ? kColorRed : kColorCyan), 0);
    }
    int link_now = wifi_down ? 0 : static_cast<int>(link.load(std::memory_order_relaxed));
    if (link_now != shown_link) {
        shown_link = link_now;
        lv_label_set_text(link_label, link_now == static_cast<int>(Link::kLan)   ? "LAN"
                                      : link_now == static_cast<int>(Link::kWan) ? "WAN"
                                                                                 : "");
    }

    // 5V rail.
    int mv = std::min(vbus_in.load(std::memory_order_relaxed), 99999);
    int centivolts = mv > 0 ? (mv + 5) / 10 : -1;
    if (centivolts != shown_vbus) {
        shown_vbus = centivolts;
        char buf[16];
        if (centivolts < 0) {
            snprintf(buf, sizeof(buf), "--.--V");
        } else {
            snprintf(buf, sizeof(buf), "%d.%02dV", centivolts / 100, centivolts % 100);
        }
        lv_label_set_text(vbus_label, buf);
        uint32_t color = kColorCyan;
        if (mv > 0 && mv < VBUS_LOW_WARN_MV - 200) {
            color = kColorRed;
        } else if (mv > 0 && mv < VBUS_LOW_WARN_MV) {
            color = kColorAmber;
        }
        lv_obj_set_style_text_color(vbus_label, Hex(color), 0);
    }

    int badge_now = Offline() ? 1 : 0;
    if (badge_now != shown_badge) {
        shown_badge = badge_now;
        if (badge_now) {
            lv_obj_remove_flag(badge, LV_OBJ_FLAG_HIDDEN);
        } else {
            lv_obj_add_flag(badge, LV_OBJ_FLAG_HIDDEN);
        }
    }
}

void JarvisHudDisplay::Impl::UpdatePanels() {
    uint32_t m = mask_in.load(std::memory_order_relaxed);
    if (m != shown_mask && (m & kPackedValid)) {
        shown_mask = m;
        auto kind = static_cast<MaskState::Kind>(m & 0x3u);
        int position = static_cast<int>((m >> 8) & 0xFFu);
        int target = static_cast<int>((m >> 16) & 0xFFu);
        char buf[16];
        uint32_t color = kColorCyan;
        if (kind == MaskState::Kind::kMoving) {
            snprintf(buf, sizeof(buf), "%d%%", position);
            lv_label_set_text(mask_icon, target >= position ? MATERIAL_SYMBOLS_ARROW_UPWARD
                                                            : MATERIAL_SYMBOLS_ARROW_DOWNWARD);
            lv_obj_remove_flag(mask_icon, LV_OBJ_FLAG_HIDDEN);
            lv_obj_set_x(mask_label, 18);
            color = kColorAmber;
        } else {
            if (kind == MaskState::Kind::kClosed || position <= 0) {
                snprintf(buf, sizeof(buf), "CLOSED");
            } else if (position >= 100) {
                snprintf(buf, sizeof(buf), "OPEN");
            } else {
                snprintf(buf, sizeof(buf), "%d%%", position);
            }
            lv_obj_add_flag(mask_icon, LV_OBJ_FLAG_HIDDEN);
            lv_obj_set_x(mask_label, 0);
        }
        lv_label_set_text(mask_label, buf);
        lv_obj_set_style_text_color(mask_label, Hex(color), 0);
        lv_obj_set_width(mask_fill, kBarW * position / 100);
        lv_obj_set_style_bg_color(mask_fill, Hex(color), 0);
    }

    uint32_t e = eyes_in.load(std::memory_order_relaxed);
    if (e != shown_eyes && (e & kPackedValid)) {
        shown_eyes = e;
        bool on = (e & 1u) != 0;
        int brightness = on ? static_cast<int>((e >> 8) & 0xFFu) : 0;
        char buf[16];
        if (on) {
            snprintf(buf, sizeof(buf), "ON %d%%", brightness);
        } else {
            snprintf(buf, sizeof(buf), "OFF");
        }
        lv_label_set_text(eyes_label, buf);
        lv_obj_set_style_text_color(eyes_label, Hex(on ? kColorCyan : kColorTextDim), 0);
        int fill = kBarW * brightness / 100;
        lv_obj_set_width(eyes_fill, fill);
        lv_obj_set_x(eyes_fill, kBarW - fill);
    }
}

void JarvisHudDisplay::Impl::UpdateModeTimeouts(uint32_t now) {
    // Upstream never re-sends STANDBY after the first server error (last_error_message_ is
    // not cleared on WebSocket), and an activation that finishes while the device is
    // already Idle (PTT pressed during the OTA retries) sends no new state either, so the
    // device state is the ground truth for Idle.
    DeviceState state = Application::GetInstance().GetDeviceState();
    const uint32_t age = now - mode_since;
    if (state == kDeviceStateIdle &&
        (mode == Mode::kListening || mode == Mode::kSpeaking || mode == Mode::kConnecting ||
         (mode == Mode::kBoot && age > kBootIdleGraceMs) ||
         (mode == Mode::kThinking && (reply_pending || age > kThinkingTimeoutMs)) ||
         (mode == Mode::kError && age > kErrorDecayMs))) {
        SetMode(Mode::kIdle, now);
        reply_pending = false;
        status_text = Lang::Strings::STANDBY;
    } else if (mode == Mode::kThinking && age > kThinkingTimeoutMs) {
        // No reply text or audio yet: fall back to what the device is doing.
        reply_pending = false;
        if (state == kDeviceStateSpeaking) {
            SetMode(Mode::kSpeaking, now);
        } else if (state == kDeviceStateListening) {
            SetMode(Mode::kListening, now);
        } else {
            SetMode(Mode::kIdle, now);
            status_text = Lang::Strings::STANDBY;
        }
    }
}

