void JarvisHudDisplay::UpdateStatusBar(bool update_all) {
    // Main task, every second: gather what needs board calls, the HUD timer renders it.
    const char* icon = Board::GetInstance().GetNetworkStateIcon();
    impl_->net_icon.store(icon, std::memory_order_relaxed);
    if (update_all || (impl_->link.load(std::memory_order_relaxed) ==
                           static_cast<uint8_t>(Link::kUnknown) &&
                       impl_->status_bar_calls % 10 == 0)) {
        Settings settings("websocket", false);
        std::string url = settings.GetString("url");
        Link kind = url.empty() ? Link::kUnknown
                    : url.rfind("wss://", 0) == 0 ? Link::kWan
                                                  : Link::kLan;
        impl_->link.store(static_cast<uint8_t>(kind), std::memory_order_relaxed);
    }
    ++impl_->status_bar_calls;
    impl_->status_dirty.store(true, std::memory_order_relaxed);
}

bool JarvisHudDisplay::SetTextFont(std::shared_ptr<LvglFont> text_font) {
    if (text_font == nullptr || text_font->font() == nullptr) {
        return false;
    }
    // Keep the stock behaviour (themes use the assets font) ...
    if (!SpiLcdDisplay::SetTextFont(text_font)) {
        return false;
    }
    // ... and chain that font behind the HUD fonts so characters outside the Vietnamese set
    // (CJK, symbols from the LLM) still render. The HUD labels keep their own fonts.
    DisplayLockGuard lock(this);
    if (impl_->vi16 != nullptr) {
        impl_->vi16->SetFallback(text_font->font());
        impl_->vi14->SetFallback(text_font->font());
    }
    impl_->asset_font = std::move(text_font);  // the previous font is released after rebinding
    if (impl_->root != nullptr) {
        lv_obj_invalidate(impl_->root);
    }
    return true;
}

