// Updates tick lengths and invalidates only the ticks that moved.
void JarvisHudDisplay::Impl::SetTickLengths(const uint8_t* lens) {
    for (int i = 0; i < kTickCount; ++i) {
        if (lens[i] == tick_len[i]) {
            continue;
        }
        const float r1 = static_cast<float>(kTickInnerR + std::max(lens[i], tick_len[i]));
        const float x0 = tick_cx + tick_cos[i] * kTickInnerR;
        const float y0 = tick_cy + tick_sin[i] * kTickInnerR;
        const float x1 = tick_cx + tick_cos[i] * r1;
        const float y1 = tick_cy + tick_sin[i] * r1;
        lv_area_t area;
        area.x1 = static_cast<int32_t>(std::floor(std::min(x0, x1))) - kTickWidth - 1;
        area.y1 = static_cast<int32_t>(std::floor(std::min(y0, y1))) - kTickWidth - 1;
        area.x2 = static_cast<int32_t>(std::ceil(std::max(x0, x1))) + kTickWidth + 1;
        area.y2 = static_cast<int32_t>(std::ceil(std::max(y0, y1))) + kTickWidth + 1;
        tick_len[i] = lens[i];
        lv_obj_invalidate_area(ticks, &area);
    }
}

void JarvisHudDisplay::Impl::OnDrawTicks(lv_event_t* e) {
    auto* self = static_cast<Impl*>(lv_event_get_user_data(e));
    lv_layer_t* layer = lv_event_get_layer(e);
    if (self == nullptr || layer == nullptr) {
        return;
    }
    lv_draw_line_dsc_t dsc;
    lv_draw_line_dsc_init(&dsc);
    dsc.color = self->tick_color;
    dsc.opa = self->tick_opa;
    dsc.width = kTickWidth;
    for (int i = 0; i < kTickCount; ++i) {
        if (self->tick_len[i] == 0) {
            continue;
        }
        const float r1 = static_cast<float>(kTickInnerR + self->tick_len[i]);
        dsc.p1.x = static_cast<lv_value_precise_t>(
            std::lround(self->tick_cx + self->tick_cos[i] * kTickInnerR));
        dsc.p1.y = static_cast<lv_value_precise_t>(
            std::lround(self->tick_cy + self->tick_sin[i] * kTickInnerR));
        dsc.p2.x = static_cast<lv_value_precise_t>(std::lround(self->tick_cx + self->tick_cos[i] * r1));
        dsc.p2.y = static_cast<lv_value_precise_t>(std::lround(self->tick_cy + self->tick_sin[i] * r1));
        lv_draw_line(layer, &dsc);
    }
}

void JarvisHudDisplay::Impl::AnimateReactor(uint32_t now) {
    const int t = static_cast<int>(now % 3600000u);  // degrees below wrap cleanly per hour
    switch (visual) {
        case Visual::kIdle: {
            // Dim cyan breathing, 3 s period; quantised so LVGL redraws ~10 times a second.
            float phase = static_cast<float>(now % kBreathePeriodMs) / kBreathePeriodMs;
            float b = 0.5f - 0.5f * std::cos(phase * 6.2831853f);
            int opa = (70 + static_cast<int>(b * 120.0f)) & ~7;
            for (int i = 0; i < 3; ++i) {
                SetRingOpa(i, opa);
            }
            SetCoreOpa(opa + 40);
            break;
        }
        case Visual::kBoot:
            SetRingRotation(1, t * 120 / 1000);
            break;
        case Visual::kConnecting:
            SetRingRotation(1, t * 200 / 1000);
            SetRingRotation(2, -t * 140 / 1000);
            break;
        case Visual::kListening: {
            // Outer ring grows with the microphone level, centred at the top.
            float level = std::clamp(mic_level, 0.0f, 1.0f);
            int span = (40 + static_cast<int>(level * 320.0f)) & ~3;
            if (span >= 360) {
                SetRingAngles(0, 0, 360);
            } else {
                SetRingAngles(0, 270 - span / 2, 270 + span / 2);
            }
            SetRingWidth(0, 2 + static_cast<int>(std::lround(level * 5.0f)));
            SetRingRotation(1, t * 40 / 1000);
            SetRingRotation(2, -t * 60 / 1000);
            break;
        }
        case Visual::kThinking:
            SetRingRotation(0, t * 100 / 1000);
            SetRingRotation(1, -t * 170 / 1000);
            SetRingRotation(2, t * 240 / 1000);
            break;
        case Visual::kSpeaking: {
            // Ticks follow the speaker level as a travelling wave.
            float level = std::clamp(spk_level, 0.0f, 1.0f);
            float phase = static_cast<float>(now % 1047u) * (6.2831853f / 1047.0f);
            uint8_t lens[kTickCount];
            for (int i = 0; i < kTickCount; ++i) {
                float wave = 0.55f + 0.45f * std::sin(static_cast<float>(i) * 0.9f + phase);
                int len = 1 + static_cast<int>(std::lround(level * kTickMaxLen * wave));
                lens[i] = static_cast<uint8_t>(std::clamp(len, 1, kTickMaxLen));
            }
            SetTickLengths(lens);
            SetRingRotation(1, t * 30 / 1000);
            SetRingOpa(2, (150 + static_cast<int>(level * 105.0f)) & ~7);
            break;
        }
        case Visual::kAlert: {
            bool on = (now % kBlinkPeriodMs) < kBlinkOnMs;
            int opa = on ? LV_OPA_COVER : 64;
            for (int i = 0; i < 3; ++i) {
                SetRingOpa(i, opa);
            }
            SetCoreOpa(opa);
            break;
        }
    }
}

void JarvisHudDisplay::Impl::AnimateCard(uint32_t now) {
    if (card == nullptr || card_state == Card::kHidden) {
        return;
    }
    const int height = static_cast<int>(owner->height_);
    const uint32_t elapsed = now - card_anim_start;
    switch (card_state) {
        case Card::kIn: {
            if (elapsed >= kCardSlideInMs) {
                card_state = Card::kShown;
                lv_obj_set_y(card, card_y);
            } else {
                // Ease-out cubic.
                float p = 1.0f - static_cast<float>(elapsed) / kCardSlideInMs;
                float k = 1.0f - p * p * p;
                lv_obj_set_y(card, height - static_cast<int>(k * static_cast<float>(height - card_y)));
            }
            break;
        }
        case Card::kShown:
            card_scroll.Tick(now);
            if (static_cast<int32_t>(card_until - now) <= 0) {
                card_state = Card::kOut;
                card_anim_start = now;
            }
            break;
        case Card::kOut: {
            if (elapsed >= kCardSlideOutMs) {
                card_state = Card::kHidden;
                lv_obj_add_flag(card, LV_OBJ_FLAG_HIDDEN);
            } else {
                float k = static_cast<float>(elapsed) / kCardSlideOutMs;
                lv_obj_set_y(card, card_y + static_cast<int>(k * static_cast<float>(height - card_y)));
            }
            break;
        }
        case Card::kHidden:
            break;
    }
}

