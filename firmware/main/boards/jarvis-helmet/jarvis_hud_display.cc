JarvisHudDisplay::JarvisHudDisplay(esp_lcd_panel_io_handle_t panel_io,
                                   esp_lcd_panel_handle_t panel, int width, int height,
                                   int offset_x, int offset_y, bool mirror_x, bool mirror_y,
                                   bool swap_xy)
    : SpiLcdDisplay(panel_io, panel, width, height, offset_x, offset_y, mirror_x, mirror_y,
                    swap_xy),
      impl_(new Impl(this)) {}

JarvisHudDisplay::~JarvisHudDisplay() {
    {
        DisplayLockGuard lock(this);
        if (impl_->timer != nullptr) {
            lv_timer_delete(impl_->timer);
        }
        if (impl_->root != nullptr) {
            lv_obj_delete(impl_->root);
        }
    }
    delete impl_;
}

void JarvisHudDisplay::SetupUI() {
    if (setup_ui_called_) {
        ESP_LOGW(TAG, "SetupUI() called multiple times, skipping duplicate call");
        return;
    }
    // The stock widgets stay alive (hidden): inherited code such as LcdDisplay::SetTheme and
    // the notification timer dereferences them without null checks.
    SpiLcdDisplay::SetupUI();

    DisplayLockGuard lock(this);
    for (lv_obj_t* obj : {container_, emoji_box_, preview_image_, top_bar_, status_bar_,
                          bottom_bar_, low_battery_popup_}) {
        if (obj != nullptr) {
            lv_obj_add_flag(obj, LV_OBJ_FLAG_HIDDEN);
        }
    }
    impl_->CreateFonts();
    impl_->Build(lv_screen_active(), width_, height_);
    impl_->timer = lv_timer_create(Impl::OnTimer, kFramePeriodMs, impl_);
    ESP_LOGI(TAG, "HUD ready");
}

void JarvisHudDisplay::Impl::CreateFonts() {
    vi16 = std::make_unique<LvglBuiltInFont>(&font_jarvis_vi_16_4);
    vi14 = std::make_unique<LvglBuiltInFont>(&font_jarvis_vi_14_4);
    hud16 = std::make_unique<LvglBuiltInFont>(&font_jarvis_hud_16_4);
    // Labels in the technical font fall back to Noto Sans for anything outside ASCII.
    hud16->SetFallback(vi16->font());
    if (asset_font != nullptr && asset_font->font() != nullptr) {
        vi16->SetFallback(asset_font->font());
        vi14->SetFallback(asset_font->font());
    }
}

void JarvisHudDisplay::Impl::Build(lv_obj_t* screen, int width, int height) {
    // Created last on the screen, so it is the topmost object; being opaque, LVGL starts
    // drawing from it and never renders the hidden stock UI underneath.
    root = MakeBox(screen, 0, 0, width, height);
    lv_obj_set_style_bg_color(root, Hex(kColorBg), 0);
    lv_obj_set_style_bg_opa(root, LV_OPA_COVER, 0);
    lv_obj_set_style_text_font(root, vi14->font(), 0);
    lv_obj_set_style_text_color(root, Hex(kColorCyan), 0);

    BuildStatusBar(width);
    BuildReactor(width);
    BuildPanels(width);
    BuildChat(width, height);
    BuildCard(width, height);
    if (owner->hide_subtitle_) {
        lv_obj_add_flag(chat, LV_OBJ_FLAG_HIDDEN);
    }

    lv_obj_update_layout(root);
    lv_area_t area;
    lv_obj_get_coords(ticks, &area);
    tick_cx = area.x1 + (lv_area_get_width(&area) - 1) / 2.0f;
    tick_cy = area.y1 + (lv_area_get_height(&area) - 1) / 2.0f;

    const uint32_t now = lv_tick_get();
    mode_since = now;
    if (status_text.empty()) {
        status_text = Lang::Strings::INITIALIZING;
    }
    ApplyVisual();
    RefreshCaption(now);
}

