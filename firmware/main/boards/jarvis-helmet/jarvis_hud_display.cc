// Copies at most max_bytes of s without splitting a UTF-8 sequence; adds "…" when cut.
std::string Clip(const char* s, size_t max_bytes) {
    if (s == nullptr) {
        return {};
    }
    size_t len = strnlen(s, max_bytes + 1);
    if (len <= max_bytes) {
        return std::string(s, len);
    }
    size_t cut = max_bytes;
    while (cut > 0 && (static_cast<unsigned char>(s[cut]) & 0xC0) == 0x80) {
        --cut;
    }
    std::string out(s, cut);
    out += "\xE2\x80\xA6";
    return out;
}

