// Packed snapshots so cross-task setters stay lock-free.
constexpr uint32_t kPackedValid = 1u << 31;

uint32_t PackMask(const MaskState& s) {
    return kPackedValid | (static_cast<uint32_t>(s.kind) & 0x3u) |
           (static_cast<uint32_t>(ClampPercent(s.position)) << 8) |
           (static_cast<uint32_t>(ClampPercent(s.target)) << 16);
}

uint32_t PackEyes(bool on, int brightness) {
    return kPackedValid | (on ? 1u : 0u) | (static_cast<uint32_t>(ClampPercent(brightness)) << 8);
}

// Removes the default theme styles and the flags a plain HUD box must not have.
lv_obj_t* MakeBox(lv_obj_t* parent, int x, int y, int w, int h) {
    lv_obj_t* box = lv_obj_create(parent);
    lv_obj_remove_style_all(box);
    lv_obj_remove_flag(box, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_remove_flag(box, LV_OBJ_FLAG_CLICKABLE);
    lv_obj_set_pos(box, x, y);
    lv_obj_set_size(box, w, h);
    return box;
}

lv_obj_t* MakeLabel(lv_obj_t* parent, const lv_font_t* font, uint32_t color, const char* text) {
    lv_obj_t* label = lv_label_create(parent);
    lv_obj_set_style_text_font(label, font, 0);
    lv_obj_set_style_text_color(label, Hex(color), 0);
    lv_label_set_text(label, text);
    return label;
}

lv_obj_t* MakeRing(lv_obj_t* parent, const RingSpec& spec) {
    lv_obj_t* arc = lv_arc_create(parent);
    lv_obj_remove_style_all(arc);
    lv_obj_remove_flag(arc, LV_OBJ_FLAG_CLICKABLE);
    lv_obj_remove_flag(arc, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_set_size(arc, spec.diameter, spec.diameter);
    lv_obj_align(arc, LV_ALIGN_CENTER, 0, 0);
    lv_arc_set_bg_angles(arc, 0, 360);
    lv_arc_set_angles(arc, spec.start, spec.start + spec.span);
    lv_obj_set_style_arc_width(arc, spec.width, LV_PART_MAIN);
    lv_obj_set_style_arc_width(arc, spec.width, LV_PART_INDICATOR);
    lv_obj_set_style_arc_rounded(arc, false, LV_PART_MAIN);
    lv_obj_set_style_arc_rounded(arc, false, LV_PART_INDICATOR);
    return arc;
}

// Line-stepped vertical scroll of a wrapped label inside a fixed-height clipping box, driven
// by the HUD timer (no extra lv_anim).
struct VScroll {
    lv_obj_t* label = nullptr;
    int box_h = 0;
    int line_h = 0;
    int overflow = 0;
    int offset = 0;
    uint32_t start_ms = 0;

    void Reset(uint32_t now) {
        offset = 0;
        overflow = 0;
        start_ms = now;
        if (label == nullptr) {
            return;
        }
        lv_obj_set_y(label, 0);
        lv_obj_update_layout(label);
        overflow = std::max(0, static_cast<int>(lv_obj_get_height(label)) - box_h);
    }

    void Tick(uint32_t now) {
        if (label == nullptr || overflow <= 0 || line_h <= 0) {
            return;
        }
        const uint32_t steps = static_cast<uint32_t>((overflow + line_h - 1) / line_h);
        const uint32_t step_ms = kScrollMoveMs + kScrollLineHoldMs;
        const uint32_t period =
            kScrollHoldTopMs + steps * step_ms + kScrollHoldBottomMs + kScrollBackMs;
        uint32_t t = (now - start_ms) % period;
        int target = 0;
        if (t < kScrollHoldTopMs) {
            target = 0;
        } else if ((t -= kScrollHoldTopMs) < steps * step_ms) {
            const int from = static_cast<int>(t / step_ms) * line_h;
            const uint32_t into = t % step_ms;
            if (into < kScrollMoveMs) {
                float p = 1.0f - static_cast<float>(into) / kScrollMoveMs;
                target = from + static_cast<int>(static_cast<float>(line_h) * (1.0f - p * p));
            } else {
                target = from + line_h;
            }
        } else if ((t -= steps * step_ms) < kScrollHoldBottomMs) {
            target = overflow;
        } else {
            t -= kScrollHoldBottomMs;
            target = overflow - static_cast<int>(static_cast<uint32_t>(overflow) * t / kScrollBackMs);
        }
        target = std::clamp(target, 0, overflow);
        if (target != offset) {
            offset = target;
            lv_obj_set_y(label, -offset);
        }
    }
};

